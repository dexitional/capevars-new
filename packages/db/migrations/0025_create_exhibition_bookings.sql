CREATE TABLE IF NOT EXISTS exhibition_bookings (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  exhibition_id INT UNSIGNED NOT NULL,
  user_id INT UNSIGNED NOT NULL,
  business_name VARCHAR(150) NOT NULL,
  contact_phone VARCHAR(30) NOT NULL,
  booths SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  products VARCHAR(1000) NULL,
  services JSON NULL,
  amount DECIMAL(10, 2) NOT NULL DEFAULT 0,
  status ENUM('requested', 'approved', 'paid', 'declined', 'cancelled') NOT NULL DEFAULT 'requested',
  organizer_note VARCHAR(1000) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_exhibition_bookings_exhibition (exhibition_id, status),
  KEY idx_exhibition_bookings_user (user_id),
  CONSTRAINT fk_exhibition_bookings_exhibition FOREIGN KEY (exhibition_id) REFERENCES exhibitions (id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_exhibition_bookings_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
