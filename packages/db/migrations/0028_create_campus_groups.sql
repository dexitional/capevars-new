CREATE TABLE IF NOT EXISTS campus_groups (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  name VARCHAR(150) NOT NULL,
  slug VARCHAR(170) NOT NULL,
  category ENUM('association', 'club', 'department', 'hall', 'faith', 'alumni', 'sports', 'professional', 'other') NOT NULL DEFAULT 'club',
  tagline VARCHAR(200) NULL,
  about TEXT NULL,
  logo_url VARCHAR(500) NULL,
  cover_url VARCHAR(500) NULL,
  visibility ENUM('public', 'private') NOT NULL DEFAULT 'public',
  join_policy ENUM('open', 'approval') NOT NULL DEFAULT 'open',
  contact_email VARCHAR(150) NULL,
  created_by INT UNSIGNED NULL,
  status ENUM('pending', 'approved', 'rejected', 'suspended') NOT NULL DEFAULT 'pending',
  status_reason VARCHAR(500) NULL,
  reviewed_by INT UNSIGNED NULL,
  reviewed_at DATETIME NULL,
  member_count INT UNSIGNED NOT NULL DEFAULT 0,
  is_featured TINYINT(1) NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_campus_groups_slug (slug),
  KEY idx_campus_groups_status (status, category),
  FULLTEXT KEY ft_campus_groups_search (name, tagline, about),
  CONSTRAINT fk_campus_groups_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_campus_groups_reviewer FOREIGN KEY (reviewed_by) REFERENCES admins (id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
