CREATE TABLE IF NOT EXISTS courses (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  instructor_id INT UNSIGNED NOT NULL,
  category_id INT UNSIGNED NULL,
  title VARCHAR(200) NOT NULL,
  slug VARCHAR(220) NOT NULL,
  subtitle VARCHAR(255) NULL,
  description MEDIUMTEXT NULL,
  outcomes JSON NULL,
  requirements JSON NULL,
  audience JSON NULL,
  level ENUM('beginner', 'intermediate', 'advanced', 'all') NOT NULL DEFAULT 'all',
  language VARCHAR(40) NOT NULL DEFAULT 'English',
  cover_url VARCHAR(500) NULL,
  promo_video_url VARCHAR(500) NULL,
  price DECIMAL(10, 2) NOT NULL DEFAULT 0,
  compare_at_price DECIMAL(10, 2) NULL,
  certificate_enabled TINYINT(1) NOT NULL DEFAULT 1,
  status ENUM('draft', 'in_review', 'published', 'rejected', 'archived') NOT NULL DEFAULT 'draft',
  review_note VARCHAR(1000) NULL,
  reviewed_by INT UNSIGNED NULL,
  submitted_at DATETIME NULL,
  published_at DATETIME NULL,
  is_featured TINYINT(1) NOT NULL DEFAULT 0,
  lesson_count INT UNSIGNED NOT NULL DEFAULT 0,
  duration_minutes INT UNSIGNED NOT NULL DEFAULT 0,
  enrollment_count INT UNSIGNED NOT NULL DEFAULT 0,
  rating_avg DECIMAL(2, 1) NULL,
  rating_count INT UNSIGNED NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_courses_slug (slug),
  KEY idx_courses_status (status, published_at),
  KEY idx_courses_instructor (instructor_id),
  KEY idx_courses_category (category_id, status),
  FULLTEXT KEY ft_courses_search (title, subtitle),
  CONSTRAINT fk_courses_instructor FOREIGN KEY (instructor_id) REFERENCES users (id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_courses_category FOREIGN KEY (category_id) REFERENCES course_categories (id) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_courses_reviewer FOREIGN KEY (reviewed_by) REFERENCES admins (id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
