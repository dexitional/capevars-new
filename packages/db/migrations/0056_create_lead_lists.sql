CREATE TABLE IF NOT EXISTS lead_lists (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id INT UNSIGNED NULL,
  title VARCHAR(200) NOT NULL,
  slug VARCHAR(220) NOT NULL,
  category ENUM('group', 'community', 'business', 'people', 'institution', 'association', 'other') NOT NULL DEFAULT 'other',
  subcategory VARCHAR(100) NULL,
  description TEXT NULL,
  cover_url VARCHAR(500) NULL,
  tags JSON NULL,
  region VARCHAR(100) NULL,
  phone_count INT UNSIGNED NOT NULL DEFAULT 0,
  email_count INT UNSIGNED NOT NULL DEFAULT 0,
  contact_count INT UNSIGNED NOT NULL DEFAULT 0,
  price DECIMAL(10, 2) NOT NULL DEFAULT 0,
  allow_download TINYINT(1) NOT NULL DEFAULT 0,
  share_code VARCHAR(16) NOT NULL,
  consent_confirmed TINYINT(1) NOT NULL DEFAULT 0,
  status ENUM('private', 'pending', 'published', 'rejected', 'suspended') NOT NULL DEFAULT 'private',
  status_reason VARCHAR(500) NULL,
  is_featured TINYINT(1) NOT NULL DEFAULT 0,
  access_count INT UNSIGNED NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_lead_lists_slug (slug),
  UNIQUE KEY uq_lead_lists_share (share_code),
  KEY idx_lead_lists_status (status, category, created_at),
  KEY idx_lead_lists_user (user_id),
  FULLTEXT KEY ft_lead_lists_search (title, subcategory, description),
  CONSTRAINT fk_lead_lists_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
