CREATE TABLE IF NOT EXISTS orders (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  order_no VARCHAR(20) NOT NULL,
  user_id INT UNSIGNED NOT NULL,
  seller_id INT UNSIGNED NOT NULL,
  status ENUM('pending', 'confirmed', 'ready', 'shipped', 'delivered', 'cancelled') NOT NULL DEFAULT 'pending',
  payment_method ENUM('online', 'cash', 'momo_direct') NOT NULL DEFAULT 'cash',
  payment_status ENUM('unpaid', 'paid', 'refunded') NOT NULL DEFAULT 'unpaid',
  fulfilment ENUM('delivery', 'pickup') NOT NULL DEFAULT 'delivery',
  subtotal DECIMAL(12, 2) NOT NULL,
  delivery_fee DECIMAL(10, 2) NOT NULL DEFAULT 0,
  total DECIMAL(12, 2) NOT NULL,
  contact_name VARCHAR(150) NOT NULL,
  contact_phone VARCHAR(30) NOT NULL,
  delivery_address VARCHAR(500) NULL,
  notes VARCHAR(1000) NULL,
  seller_note VARCHAR(1000) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_orders_no (order_no),
  KEY idx_orders_user (user_id, created_at),
  KEY idx_orders_seller (seller_id, status, created_at),
  CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_orders_seller FOREIGN KEY (seller_id) REFERENCES sellers (id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
