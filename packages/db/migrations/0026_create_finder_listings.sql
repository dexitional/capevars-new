CREATE TABLE IF NOT EXISTS finder_listings (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  type ENUM('person', 'place', 'business', 'hostel', 'hotel', 'restaurant') NOT NULL,
  user_id INT UNSIGNED NULL,
  name VARCHAR(200) NOT NULL,
  slug VARCHAR(220) NOT NULL,
  tagline VARCHAR(255) NULL,
  description TEXT NULL,
  category VARCHAR(80) NULL,
  cover_url VARCHAR(500) NULL,
  logo_url VARCHAR(500) NULL,
  images JSON NULL,
  address VARCHAR(255) NULL,
  area VARCHAR(100) NULL,
  city VARCHAR(100) NULL,
  latitude DECIMAL(10, 7) NULL,
  longitude DECIMAL(10, 7) NULL,
  phone VARCHAR(30) NULL,
  whatsapp VARCHAR(30) NULL,
  email VARCHAR(150) NULL,
  website VARCHAR(255) NULL,
  price_from DECIMAL(12, 2) NULL,
  price_to DECIMAL(12, 2) NULL,
  price_unit VARCHAR(30) NULL,
  star_rating TINYINT UNSIGNED NULL,
  amenities JSON NULL,
  opening_hours VARCHAR(200) NULL,
  attributes JSON NULL,
  rating_avg DECIMAL(2, 1) NULL,
  rating_count INT UNSIGNED NOT NULL DEFAULT 0,
  view_count INT UNSIGNED NOT NULL DEFAULT 0,
  is_verified TINYINT(1) NOT NULL DEFAULT 0,
  is_featured TINYINT(1) NOT NULL DEFAULT 0,
  status ENUM('pending', 'published', 'rejected', 'hidden') NOT NULL DEFAULT 'pending',
  status_reason VARCHAR(500) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_finder_listings_slug (slug),
  KEY idx_finder_listings_type (type, status, is_featured),
  KEY idx_finder_listings_city (city, area),
  KEY idx_finder_listings_user (user_id),
  FULLTEXT KEY ft_finder_listings_search (name, tagline, description, address, area, category),
  CONSTRAINT fk_finder_listings_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
