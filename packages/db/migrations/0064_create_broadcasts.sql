CREATE TABLE IF NOT EXISTS broadcasts (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id INT UNSIGNED NOT NULL,
  channel ENUM('sms', 'email') NOT NULL,
  sender_id INT UNSIGNED NULL,
  sender_label VARCHAR(80) NOT NULL,
  reply_to VARCHAR(150) NULL,
  subject VARCHAR(200) NULL,
  body TEXT NOT NULL,
  audience JSON NOT NULL,
  recipient_count INT UNSIGNED NOT NULL DEFAULT 0,
  units_per_message TINYINT UNSIGNED NOT NULL DEFAULT 1,
  cost_credits DECIMAL(12, 2) NOT NULL DEFAULT 0,
  refunded_credits DECIMAL(12, 2) NOT NULL DEFAULT 0,
  status ENUM('scheduled', 'queued', 'sending', 'sent', 'failed', 'cancelled') NOT NULL DEFAULT 'queued',
  scheduled_at DATETIME NULL,
  started_at DATETIME NULL,
  finished_at DATETIME NULL,
  sent_count INT UNSIGNED NOT NULL DEFAULT 0,
  failed_count INT UNSIGNED NOT NULL DEFAULT 0,
  error VARCHAR(500) NULL,
  locked_at DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_broadcasts_user (user_id, id),
  KEY idx_broadcasts_queue (status, scheduled_at),
  CONSTRAINT fk_broadcasts_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_broadcasts_sender FOREIGN KEY (sender_id) REFERENCES sender_ids (id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
