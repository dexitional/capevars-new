CREATE TABLE IF NOT EXISTS tickets (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  code VARCHAR(16) NOT NULL,
  user_id INT UNSIGNED NOT NULL,
  kind ENUM('event', 'bus') NOT NULL,
  event_id INT UNSIGNED NULL,
  ticket_type_id INT UNSIGNED NULL,
  trip_id INT UNSIGNED NULL,
  seat_no SMALLINT UNSIGNED NULL,
  holder_name VARCHAR(150) NOT NULL,
  holder_phone VARCHAR(30) NULL,
  amount DECIMAL(10, 2) NOT NULL,
  status ENUM('reserved', 'paid', 'used', 'cancelled') NOT NULL DEFAULT 'reserved',
  payment_id INT UNSIGNED NULL,
  checked_in_at DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_tickets_code (code),
  UNIQUE KEY uq_tickets_seat (trip_id, seat_no),
  KEY idx_tickets_user (user_id, created_at),
  KEY idx_tickets_event (event_id, status),
  CONSTRAINT fk_tickets_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_tickets_event FOREIGN KEY (event_id) REFERENCES ticket_events (id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_tickets_type FOREIGN KEY (ticket_type_id) REFERENCES ticket_types (id) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_tickets_trip FOREIGN KEY (trip_id) REFERENCES bus_trips (id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_tickets_payment FOREIGN KEY (payment_id) REFERENCES payments (id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
