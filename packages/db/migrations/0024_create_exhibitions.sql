CREATE TABLE IF NOT EXISTS exhibitions (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  seller_id INT UNSIGNED NULL,
  title VARCHAR(200) NOT NULL,
  slug VARCHAR(220) NOT NULL,
  theme VARCHAR(200) NULL,
  description TEXT NULL,
  cover_url VARCHAR(500) NULL,
  venue VARCHAR(200) NOT NULL,
  city VARCHAR(100) NULL,
  starts_at DATETIME NOT NULL,
  ends_at DATETIME NOT NULL,
  booth_price DECIMAL(10, 2) NOT NULL DEFAULT 0,
  booths_total SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  booths_taken SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  services JSON NULL,
  status ENUM('pending', 'published', 'rejected', 'cancelled') NOT NULL DEFAULT 'pending',
  status_reason VARCHAR(500) NULL,
  is_featured TINYINT(1) NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_exhibitions_slug (slug),
  KEY idx_exhibitions_status (status, starts_at),
  CONSTRAINT fk_exhibitions_seller FOREIGN KEY (seller_id) REFERENCES sellers (id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
