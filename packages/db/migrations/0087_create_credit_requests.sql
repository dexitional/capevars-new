CREATE TABLE IF NOT EXISTS credit_requests (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id INT UNSIGNED NOT NULL,
  reference VARCHAR(20) NOT NULL,
  credits INT UNSIGNED NOT NULL,
  amount_ghs DECIMAL(12, 2) NOT NULL,
  network VARCHAR(20) NOT NULL,
  account_name VARCHAR(100) NOT NULL,
  account_number VARCHAR(20) NOT NULL,
  transaction_id VARCHAR(40) NULL,
  payer_phone VARCHAR(20) NULL,
  status ENUM('awaiting', 'submitted', 'approved', 'rejected', 'cancelled') NOT NULL DEFAULT 'awaiting',
  alert_status VARCHAR(100) NULL,
  admin_note VARCHAR(300) NULL,
  submitted_at DATETIME NULL,
  handled_by INT UNSIGNED NULL,
  handled_at DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_credit_requests_reference (reference),
  UNIQUE KEY uq_credit_requests_transaction (network, transaction_id),
  KEY idx_credit_requests_user (user_id, id),
  KEY idx_credit_requests_status (status, id),
  CONSTRAINT fk_credit_requests_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
