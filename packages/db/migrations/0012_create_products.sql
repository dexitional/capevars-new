CREATE TABLE IF NOT EXISTS products (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  seller_id INT UNSIGNED NOT NULL,
  category_id INT UNSIGNED NULL,
  kind ENUM('product', 'food') NOT NULL DEFAULT 'product',
  title VARCHAR(200) NOT NULL,
  slug VARCHAR(220) NOT NULL,
  description TEXT NULL,
  menu_section VARCHAR(60) NULL,
  price DECIMAL(12, 2) NOT NULL,
  compare_at_price DECIMAL(12, 2) NULL,
  stock INT NULL,
  item_condition ENUM('new', 'used', 'refurbished') NOT NULL DEFAULT 'new',
  images JSON NULL,
  tags JSON NULL,
  status ENUM('active', 'draft', 'hidden', 'blocked') NOT NULL DEFAULT 'active',
  is_featured TINYINT(1) NOT NULL DEFAULT 0,
  rating_avg DECIMAL(2, 1) NULL,
  rating_count INT UNSIGNED NOT NULL DEFAULT 0,
  sold_count INT UNSIGNED NOT NULL DEFAULT 0,
  view_count INT UNSIGNED NOT NULL DEFAULT 0,
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_products_slug (slug),
  KEY idx_products_seller (seller_id, status),
  KEY idx_products_category (category_id, status),
  KEY idx_products_kind (kind, status, created_at),
  FULLTEXT KEY ft_products_search (title, description),
  CONSTRAINT fk_products_seller FOREIGN KEY (seller_id) REFERENCES sellers (id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES market_categories (id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
