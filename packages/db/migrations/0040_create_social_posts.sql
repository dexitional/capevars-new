CREATE TABLE IF NOT EXISTS social_posts (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  author_id INT UNSIGNED NOT NULL,
  page_id INT UNSIGNED NULL,
  wall_user_id INT UNSIGNED NULL,
  body TEXT NULL,
  images JSON NULL,
  link_url VARCHAR(500) NULL,
  shared_post_id INT UNSIGNED NULL,
  visibility ENUM('public', 'friends', 'only_me') NOT NULL DEFAULT 'public',
  reaction_count INT UNSIGNED NOT NULL DEFAULT 0,
  comment_count INT UNSIGNED NOT NULL DEFAULT 0,
  share_count INT UNSIGNED NOT NULL DEFAULT 0,
  is_hidden TINYINT(1) NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_social_posts_author (author_id, created_at),
  KEY idx_social_posts_page (page_id, created_at),
  KEY idx_social_posts_wall (wall_user_id, created_at),
  KEY idx_social_posts_feed (is_hidden, visibility, created_at),
  CONSTRAINT fk_social_posts_author FOREIGN KEY (author_id) REFERENCES users (id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_social_posts_page FOREIGN KEY (page_id) REFERENCES social_pages (id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_social_posts_wall FOREIGN KEY (wall_user_id) REFERENCES users (id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_social_posts_shared FOREIGN KEY (shared_post_id) REFERENCES social_posts (id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
