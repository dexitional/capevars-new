CREATE TABLE IF NOT EXISTS jobs (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id INT UNSIGNED NOT NULL,
  company_name VARCHAR(150) NOT NULL,
  company_logo_url VARCHAR(500) NULL,
  title VARCHAR(200) NOT NULL,
  slug VARCHAR(220) NOT NULL,
  category VARCHAR(60) NOT NULL,
  job_type ENUM('full_time', 'part_time', 'contract', 'internship', 'national_service', 'gig', 'volunteer') NOT NULL DEFAULT 'full_time',
  workplace ENUM('onsite', 'remote', 'hybrid') NOT NULL DEFAULT 'onsite',
  experience_level ENUM('entry', 'mid', 'senior', 'any') NOT NULL DEFAULT 'any',
  location VARCHAR(150) NOT NULL,
  salary_min DECIMAL(12, 2) NULL,
  salary_max DECIMAL(12, 2) NULL,
  salary_period ENUM('hour', 'day', 'month', 'year', 'project') NOT NULL DEFAULT 'month',
  description TEXT NOT NULL,
  skills JSON NULL,
  apply_method ENUM('platform', 'email', 'link') NOT NULL DEFAULT 'platform',
  apply_target VARCHAR(500) NULL,
  deadline DATE NULL,
  status ENUM('pending', 'published', 'closed', 'rejected') NOT NULL DEFAULT 'pending',
  status_reason VARCHAR(500) NULL,
  is_featured TINYINT(1) NOT NULL DEFAULT 0,
  view_count INT UNSIGNED NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_jobs_slug (slug),
  KEY idx_jobs_status (status, created_at),
  KEY idx_jobs_user (user_id),
  FULLTEXT KEY ft_jobs_search (title, company_name, description),
  CONSTRAINT fk_jobs_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
