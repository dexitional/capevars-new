CREATE TABLE IF NOT EXISTS credit_vouchers (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  code VARCHAR(24) NOT NULL,
  credits DECIMAL(12, 2) NOT NULL,
  max_redemptions INT UNSIGNED NOT NULL DEFAULT 1,
  redeemed_count INT UNSIGNED NOT NULL DEFAULT 0,
  expires_on DATE NULL,
  note VARCHAR(200) NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_by INT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_credit_vouchers_code (code),
  CONSTRAINT fk_credit_vouchers_admin FOREIGN KEY (created_by) REFERENCES admins (id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
