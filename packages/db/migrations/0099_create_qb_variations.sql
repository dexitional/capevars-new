CREATE TABLE IF NOT EXISTS qb_variations (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id INT UNSIGNED NOT NULL,
  name VARCHAR(120) NOT NULL,
  course_ids JSON NOT NULL,
  tag_ids JSON NOT NULL,
  exam_questions SMALLINT UNSIGNED NOT NULL DEFAULT 20,
  exam_minutes SMALLINT UNSIGNED NOT NULL DEFAULT 30,
  study_position INT UNSIGNED NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_qb_variations_user (user_id, id),
  CONSTRAINT fk_qb_variations_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
