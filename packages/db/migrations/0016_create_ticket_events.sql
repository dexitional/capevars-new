CREATE TABLE IF NOT EXISTS ticket_events (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  seller_id INT UNSIGNED NULL,
  title VARCHAR(200) NOT NULL,
  slug VARCHAR(220) NOT NULL,
  category ENUM('src', 'association', 'campus', 'private', 'concert', 'conference', 'sports', 'other') NOT NULL DEFAULT 'campus',
  summary VARCHAR(300) NULL,
  description TEXT NULL,
  cover_url VARCHAR(500) NULL,
  venue VARCHAR(200) NOT NULL,
  city VARCHAR(100) NULL,
  starts_at DATETIME NOT NULL,
  ends_at DATETIME NULL,
  status ENUM('draft', 'pending', 'published', 'rejected', 'cancelled') NOT NULL DEFAULT 'pending',
  status_reason VARCHAR(500) NULL,
  is_featured TINYINT(1) NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_ticket_events_slug (slug),
  KEY idx_ticket_events_status (status, starts_at),
  KEY idx_ticket_events_seller (seller_id),
  CONSTRAINT fk_ticket_events_seller FOREIGN KEY (seller_id) REFERENCES sellers (id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
